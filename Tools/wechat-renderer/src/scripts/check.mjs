#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { renderArticle, buildPreview } from './render.mjs';
import { videoChecklist } from './videos.mjs';

const dir = path.dirname(fileURLToPath(import.meta.url));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'wechat-black-red-check-'));
const decode = text => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
try {
  const source = '---\ntitle: Metadata title\n---\n# Original & title\n\n开头**普通粗体**与*斜体*。中间==高亮==之后。\n\n## 第一节\n\n原句 & <u>概念</u> <mark data-tone="warning">提醒</mark> <span data-tone="red">方法</span>。\n\n```js\n  const s = "<script>&\\n";\n\tconsole.log(s);\n```\n\n3. 第三项\n4. 第四项\n   - 子项\n\n| A | B |\n| :- | -: |\n| 甲 | 乙 |\n\n> [!TIP] 提示标题\n> 保持原文。\n\n## 第二节\n\n# 后续 H1 保留\n';
  const result = renderArticle(source);
  assert.deepEqual(result, renderArticle(source), 'Identical input produces identical outputs');
  assert.equal(result.title, 'Original & title');
  assert.equal(result.report.sections, 2);
  assert(!result.html.includes('Original &amp; title'));
  assert(result.html.includes('后续 H1 保留'));
  assert(result.html.includes('background:#f7e4e5'));
  assert(!result.html.includes('==高亮=='));
  assert(result.html.includes('background:#fff1bf'));
  assert(result.html.includes('提示标题'));
  assert(result.html.includes('保持原文。'));
  const sourceLabels = renderArticle('## 01. 原有编号\n\n> [!TIP] **原有标题**\n> 原有内容\n\n> [!END]\n> 原有结尾\n\n## Section 09 原有英文标题');
  assert(sourceLabels.html.includes('01. 原有编号'));
  assert(sourceLabels.html.includes('Section 09 原有英文标题'));
  for (const text of ['原有标题', '原有内容', '原有结尾']) {
    assert.equal(sourceLabels.html.split(text).length - 1, 1, 'Callout content is preserved exactly once');
  }
  assert(!sourceLabels.html.includes('>TIP<'));
  assert(!sourceLabels.html.includes('End Note'));
  assert(!result.html.includes('Section 01'));
  assert(result.html.includes('start="3"'));
  assert(result.html.includes('text-align:right'));
  assert.equal(decode(result.html.match(/<pre[^>]*><code[^>]*>([\s\S]*?)<\/code><\/pre>/)[1]), '  const s = "<script>&\\n";\n\tconsole.log(s);\n');
  assert(!/<script[\s>]|<style[\s>]| class=/.test(result.html));
  assert.equal((result.html.match(/mp-style-type data-value="3"/g) || []).length, 1);
  assert.deepEqual(renderArticle('只是**粗体**与文字。').report.warnings, []);
  assert(!renderArticle('只是**粗体**与文字。').html.includes('background:#f7e4e5'));

  const unsafe = renderArticle('正文 <script>alert(1)</script>\n\n[[未转换链接]]\n\n脚注[^1]\n\n$x+y$');
  assert(unsafe.report.requiresReview);
  assert(unsafe.html.includes('&lt;script&gt;'));
  assert(unsafe.html.includes('[[未转换链接]]'));
  assert(!unsafe.html.includes('<script>'));
  assert(!buildPreview({ ...unsafe, title: '</script><script>alert(1)</script>' }).includes('</script><script>alert(1)</script>'));
  assert.throws(() => renderArticle('---\ntitle: missing end'), /结束分隔线/);
  assert.equal(renderArticle('---\ntitle: |\n  多行标题\n---\n\n正文').title, '多行标题');

  const videoSource = '---\ntitle: 视频文章\n---\n# 视频文章\n\n## 操作流程\n\n前文。\n\n```wechat-video\ntitle: 实际演示\nsource: https://example.com/demo.mp4?sig=a%2Bb&x=1\n```\n\n后文。\n\n![第二处](https://example.com/demo.mp4?sig=a%2Bb&x=1)\n\n[腾讯视频](https://v.qq.com/x/page/example.html)';
  const videoResult = renderArticle(videoSource);
  assert.equal(videoResult.report.videos.length, 3);
  assert.equal(videoResult.report.images.length, 0, 'Video embeds are not sent to the image loader');
  assert.deepEqual(videoResult.report.videos.map(v=>v.number), ['01','02','03']);
  assert.equal(videoResult.report.videos[0].sourceLine, 10, 'Line numbers include frontmatter and removed title');
  assert.equal(videoResult.report.videos[0].section, '操作流程');
  assert.equal(videoResult.report.videos[0].source, 'https://example.com/demo.mp4?sig=a%2Bb&x=1');
  assert(videoResult.html.indexOf('前文。') < videoResult.html.indexOf('在此插入视频'));
  assert(videoResult.html.indexOf('实际演示') < videoResult.html.indexOf('后文。'));
  assert(!/<video[\s>]|<iframe[\s>]/.test(videoResult.html));
  assert(videoChecklist(videoResult.report.videos).includes('- [ ] 删除对应的整张占位卡'));
  assert.equal(renderArticle('请看[这个视频](https://example.com/demo.mp4)，再继续。\n\n```text\nhttps://example.com/demo.mp4\n```').report.videos.length, 0);
  assert.equal(renderArticle('https://example.com/demo.mp4').report.videos.length, 1);
  assert.throws(()=>renderArticle('```wechat-video\ntitle: 没有来源\n```'), /source/);
  assert.throws(()=>renderArticle('```wechat-video\nsource: javascript:alert(1)\n```'), /协议/);
  assert.throws(()=>renderArticle('```wechat-video\nsource: demo.mp4\nextra: 不能静默丢弃\n```'), /title 和 source/);

  const inputPath = path.join(tmp, '文章.md');
  fs.writeFileSync(path.join(tmp, '演示.mp4'), 'test fixture, not playable video');
  const localVideo = renderArticle('![本地演示](演示.mp4)', { inputPath });
  assert.equal(localVideo.report.videos[0].exists, true);
  assert.equal(localVideo.report.videos[0].status, 'pending-wechat-insertion');
  assert.equal(renderArticle('![缺少文件](missing.mp4)', { inputPath }).report.videos[0].exists, false);
  assert.throws(() => renderArticle('![missing](missing.png)', { inputPath }), /不存在/);
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
  fs.writeFileSync(path.join(tmp, '一 张图.png'), png);
  const local = renderArticle('![原始图注](一%20张图.png)', { inputPath });
  assert(local.html.includes('data:image/png;base64,'));
  assert(local.html.includes('<figcaption'));
  assert.equal(local.report.images[0].kind, 'local');
  assert(local.report.requiresReview);
  assert.equal(local.report.imageCopyEligible, true);
  assert.equal(renderArticle('![远程图](https://example.com/a.gif)').report.images[0].kind, 'remote');
  const hostedUrl = 'https://image.example.com/CaseSensitive.png?sign=ab%2Bcd&expires=123';
  const mapped = renderArticle('![原始图注](一%20张图.png)', { inputPath, imageMap: { '一 张图.png': hostedUrl } });
  assert.equal(mapped.report.images[0].url, hostedUrl);
  assert.equal(mapped.report.imageCopyEligible, true);
  assert(!mapped.html.includes('data:image/'));
  assert(mapped.html.includes('sign=ab%2Bcd&amp;expires=123'));
  assert(mapped.html.includes('referrerpolicy="no-referrer"'));
  assert(!mapped.html.includes('crossorigin'));
  // Themes change presentation, never content or media routing; calls stay isolated.
  const paper = renderArticle(source, { theme: 'blueprint' });
  assert.equal(paper.report.theme, 'blueprint');
  assert.notEqual(paper.report.template, result.report.template);
  assert.equal(paper.report.sourceSha256, result.report.sourceSha256);
  const content = html => decode(html.replace(/<span[^>]*data-theme-ornament="heading"[^>]*>[\s\S]*?<\/span>/g, '').replace(/<[^>]*>/g, '')).replace(/●/g, '').replace(/\s/g, '');
  assert.equal(content(paper.html), content(result.html));
  assert.equal((paper.html.match(/●/g) || []).length, 3, 'Blueprint code window keeps three real traffic-light characters');
  assert.equal((paper.html.match(/data-theme-ornament="heading"/g) || []).length, paper.report.sections);
  const longText = '长'.repeat(301);
  const quoteFixture = '> ' + longText + '\n\n> ' + '短'.repeat(300) + '\n\n> [!TIP] 保留提示卡\n> ' + longText;
  assert(!renderArticle(quoteFixture, { theme: 'blueprint' }).html.includes('data-scroll-quote'));
  const scrollQuotes = renderArticle(quoteFixture, { theme: 'blueprint', scrollLongQuotes: true });
  assert.equal(scrollQuotes.report.scrollQuotes.count, 1);
  assert(scrollQuotes.html.includes(longText));
  assert(scrollQuotes.html.includes('height:240px;overflow-y:auto;'));
  assert.equal((scrollQuotes.html.match(/<blockquote /g) || []).length, 1);
  assert(scrollQuotes.html.includes('保留提示卡'));
  assert(!renderArticle('> ' + longText + '\n>\n> > 嵌套', { theme: 'blueprint', scrollLongQuotes: true }).html.includes('data-scroll-quote'));
  const numbered = renderArticle('## 开始\n\n### 子节\n\n## 下一节\n\n## 03. 原文编号', { theme: 'blueprint' });
  assert.deepEqual([...numbered.html.matchAll(/data-theme-ornament="heading"[^>]*>(\d+)<\/span>/g)].map(m => m[1]), ['01', '02', '03']);
  assert(numbered.html.includes('03. 原文编号'), 'Source title is preserved even when it contains a number');
  assert(!result.html.includes('data-theme-ornament="heading"'), 'Black-red headings stay unnumbered');
  const tocSource = '引言\n\n## **同名** 与 `code`\n\n### 子标题\n\n## **同名** 与 `code`\n\n```md\n<!-- toc -->\n```';
  const tocResult = renderArticle(tocSource, { theme: 'blueprint', toc: true });
  assert.deepEqual(tocResult.report.toc.entries.map(e => e.title), ['同名 与 code', '同名 与 code']);
  assert.deepEqual(tocResult.report.toc.entries.map(e => e.id), ['article-section-01', 'article-section-02']);
  assert.equal((tocResult.html.match(/data-article-toc=/g) || []).length, 1);
  assert(tocResult.html.indexOf('引言') < tocResult.html.indexOf('data-article-toc='));
  assert(tocResult.html.indexOf('data-article-toc=') < tocResult.html.indexOf('<h2'));
  assert(tocResult.html.includes('href="#article-section-02"'));
  assert(tocResult.html.includes('id="article-section-02"'));
  assert(tocResult.html.includes('&lt;!-- toc --&gt;'), 'A marker inside code stays literal');
  assert(!renderArticle(tocSource).html.includes('data-article-toc'));
  const placed = renderArticle('<!-- toc -->\n\n引言\n\n## 后文', { toc: true });
  assert(placed.html.indexOf('data-article-toc=') < placed.html.indexOf('引言'));
  assert(!placed.html.includes('&lt;!-- toc --&gt;'));
  assert(!renderArticle('<!-- toc -->\n\n无章节', { toc: true }).html.includes('data-article-toc'));
  assert.throws(() => renderArticle('<!-- toc -->\n\n<!-- toc -->\n\n## 章节', { toc: true }), /只能放置一个/);
  assert.equal(renderArticle(tocSource, { toc: true }).report.sections, 2);
  const hostileHeading = renderArticle('## <script>alert(1)</script>', { toc: true });
  assert(!hostileHeading.html.includes('<script>'));
  assert.deepEqual(renderArticle(source, { theme: 'paper-notes' }), paper, 'Legacy paper theme resolves to its replacement');
  assert(result.html.includes('●'));
  assert.deepEqual(renderArticle(source), result, 'Selecting paper does not mutate default theme');
  const songti = renderArticle(source, { theme: 'songti-supplement' });
  assert.equal(content(songti.html), content(result.html), 'Songti preserves text and code content');
  assert.equal(songti.report.theme, 'songti-supplement');
  assert(!songti.html.includes('data-theme-ornament'));
  assert(!songti.html.includes('data-article-toc'));
  assert.deepEqual(renderArticle(videoSource, { theme: 'songti-supplement' }).report.videos, videoResult.report.videos);
  assert.deepEqual(renderArticle('![原始图注](一%20张图.png)', { inputPath, theme: 'songti-supplement', imageMap: { '一 张图.png': hostedUrl } }).report.images, mapped.report.images);
  assert.equal(renderArticle('![本地图](一%20张图.png)', { inputPath, theme: 'songti-supplement' }).report.imageCopyEligible, true);
  assert(buildPreview(songti).includes('宋体副刊 / 固定模板'));
  assert(!buildPreview(songti).includes('<!--PREVIEW_TITLE_STYLE-->'));
  assert.deepEqual(renderArticle(source), result, 'Songti does not mutate default theme');
  assert.deepEqual(renderArticle(source, { theme: 'black-red' }), result);
  assert.equal(buildPreview(paper).includes('蓝图档案 / 固定模板'), true);
  assert(!buildPreview(paper).includes('黑红刊刻风'));
  assert.deepEqual(renderArticle(videoSource, { theme: 'blueprint' }).report.videos, videoResult.report.videos);
  const paperMapped = renderArticle('![原始图注](一%20张图.png)', { inputPath, theme: 'blueprint', imageMap: { '一 张图.png': hostedUrl } });
  assert.deepEqual(paperMapped.report.images, mapped.report.images);
  assert.equal(renderArticle('![图](一%20张图.png)', { inputPath, theme: 'blueprint' }).report.imageCopyEligible, true);
  assert.throws(() => renderArticle(source, { theme: '../theme' }), /未知主题/);
  assert.throws(() => renderArticle(source, { theme: 'toString' }), /未知主题/);
  assert.throws(() => renderArticle('正文', { imageMap: { a: 'javascript:alert(1)' } }), /HTTPS/);
  assert.equal(renderArticle('![](//image.example.com/a.png)').report.images[0].url, 'https://image.example.com/a.png');

  fs.writeFileSync(inputPath, source);
  const out = path.join(tmp, 'result');
  const cli = (...extra) => spawnSync(process.execPath, [path.join(dir, 'render.mjs'), '--input', inputPath, '--out-dir', out, ...extra], { encoding: 'utf8' });
  assert.equal(cli().status, 0);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(out, 'videos.json'), 'utf8')), []);
  const first = fs.readFileSync(path.join(out, 'article.html'));
  assert.equal(cli().status, 0, 'Identical reruns are allowed');
  assert.equal(cli('--theme', 'blueprint').status, 1, 'Theme changes also require overwrite');
  assert.equal(cli('--theme', 'missing', '--overwrite').status, 1);
  assert.deepEqual(fs.readFileSync(path.join(out, 'article.html')), first, 'Invalid themes do not modify output');
  assert.equal(cli('--theme', 'blueprint', '--overwrite').status, 0);
  assert.equal(JSON.parse(fs.readFileSync(path.join(out, 'report.json'))).theme, 'blueprint');
  assert.equal(cli('--theme', 'black-red', '--overwrite').status, 0);
  assert.deepEqual(fs.readFileSync(path.join(out, 'article.html')), first);
  assert.equal(cli('--toc', '--overwrite').status, 0);
  assert(JSON.parse(fs.readFileSync(path.join(out, 'report.json'))).toc.enabled);
  assert.equal(cli('--overwrite').status, 0);
  assert.deepEqual(fs.readFileSync(path.join(out, 'article.html')), first, 'Turning TOC off restores original body');
  fs.writeFileSync(inputPath, source + '\n新增句子。');
  assert.equal(cli().status, 1, 'Changed output is protected without --overwrite');
  assert.deepEqual(fs.readFileSync(path.join(out, 'article.html')), first);
  assert.equal(cli('--overwrite').status, 0);
  assert.equal(fs.readFileSync(inputPath, 'utf8'), source + '\n新增句子。');
  fs.writeFileSync(inputPath, '![图注](missing.png)');
  const mappingPath = path.join(tmp, 'images.json');
  fs.writeFileSync(mappingPath, JSON.stringify({ 'missing.png': hostedUrl }));
  assert.equal(cli('--overwrite', '--image-map', mappingPath).status, 0, 'Uploaded images can replace missing local files without editing the source');
  assert.equal(fs.readFileSync(inputPath, 'utf8'), '![图注](missing.png)');
  const alias = path.join(tmp, 'skill');
  fs.symlinkSync(path.resolve(dir, '..'), alias);
  const linkedRun = spawnSync(process.execPath, [path.join(alias, 'scripts/render.mjs'), '--help'], { encoding: 'utf8' });
  assert.equal(linkedRun.status, 0);
  assert(linkedRun.stdout.includes('--input'), 'Installed symlink invocation runs the CLI');
  console.log('PASS: deterministic rendering, title separation, explicit emphasis, code and list preservation, HTML escaping, image errors, output protection and linked installation.');
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
